#!/usr/bin/env python3
"""Compile the judge comparison tables from results/votes.csv and labels/labels.csv.

  python scoring/judges/validation/kit/compile_table.py          # rewrites results/table.md, table_full.md, results.json
  python scoring/judges/validation/kit/compile_table.py --check  # exit 1 if the committed tables are stale

Per configuration: majority verdict over its passes per cell (ties to the worse label, the released rule),
scored binary (correct versus not correct) against the human label. Reweighted columns give each sampling-judge
stratum its share of the 459-cell population (labels/sampling.json). Costs come from results/configurations.json.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import (CALLS_PER_VERIFIED_SUBMISSION, VALIDATION_DIR, majority, metrics,  # noqa: E402
                    read_json, read_labels, read_votes, stratum_weights, votes_of)


def fmt(x, pct=False):
    if x is None:
        return "n/a"
    return f"{100 * x:.1f}%" if pct else f"{x:.3f}"


def money(x):
    return "n/a" if x is None else f"${x:,.2f}"


def compile_all():
    labels = {r["cell"]: r for r in read_labels()}
    vote_rows, configs = read_votes()
    rows = []
    for v in vote_rows:
        r = dict(labels[v["cell"]])
        r.update({c: v[c] for c in configs})
        rows.append(r)
    population = read_json("labels/sampling.json")["population_by_sampling_judge_majority"]
    weights = stratum_weights(rows, population)
    conf = read_json("results/configurations.json")

    results = {}
    for c in configs:
        per_cell = {r["cell"]: votes_of(r, c) for r in rows}
        passes = max(len(v) for v in per_cell.values())
        maj = {cell: majority(v) for cell, v in per_cell.items() if v}
        res = {"passes": passes, "cells": sum(1 for v in per_cell.values() if v),
               "cells_with_all_passes": sum(len(v) == passes for v in per_cell.values()),
               "majority": metrics(rows, lambda r: maj.get(r["cell"]), weights),
               "single_pass": [metrics(rows, lambda r, i=i: (votes_of(r, c)[i] if len(votes_of(r, c)) > i else None), weights)
                               for i in range(passes)]}
        full = [v for v in per_cell.values() if len(v) == passes]
        res["unanimous_share"] = (sum(len(set(v)) == 1 for v in full) / len(full)) if full and passes > 1 else None
        info = conf.get(c, {})
        per_call = None
        if info.get("calls") and info.get("cost_usd") is not None:
            per_call = info["cost_usd"] / info["calls"]
        elif info.get("cost_per_call_from"):
            src = conf[info["cost_per_call_from"]]
            per_call = src["cost_usd"] / src["calls"]
        res["cost_per_call_usd"] = per_call
        res["cost_per_verified_submission_usd"] = per_call * CALLS_PER_VERIFIED_SUBMISSION if per_call is not None else None
        results[c] = res

    # the floor: a judge that never says correct
    floor = metrics(rows, lambda r: "missing", weights)
    return rows, configs, conf, weights, results, floor


def curated_table(conf, results, floor):
    spec = read_json("results/curated_rows.json")
    lines = ["| Judge | Prompt | Cohen's kappa | Raw agreement | Cost per verified submission | Model status | Model string |",
             "|---|---|---|---|---|---|---|",
             f"| Always \"not correct\" (floor) | none | {fmt(floor['kappa'])} | {fmt(floor['agreement'], True)} | $0 | | |"]
    for s in spec:
        c = s["configuration"]
        m = results[c]["majority"]
        cells = [s["judge"], s["prompt"], fmt(m["kappa"]), fmt(m["agreement"], True),
                 money(results[c]["cost_per_verified_submission_usd"]), s.get("status", ""), f"`{conf[c]['model']}`"]
        if s.get("selected"):
            cells = [f"**{x}**" if x and not x.startswith("`") else x for x in cells]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def full_table(conf, configs, results, floor, n_labelled):
    L = ["# Every judge configuration scored on the labelled cells", "",
         f"Majority verdict over the configuration's passes per cell (ties to the worse label), binary correct versus not correct against the human label, {n_labelled} labelled cells. Reweighted columns give each sampling-judge stratum its share of the 459-cell population. Generated by `kit/compile_table.py` from `results/votes.csv` and `labels/labels.csv`; edit nothing here by hand.", "",
         "| Configuration | Model string | Prompt | Passes | Cohen's kappa | Raw agreement | Kappa, reweighted | Agreement, reweighted | Unanimous cells | Calls | Logged cost | Per-call outputs |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|",
         f"| always \"not correct\" (floor) | | | | {fmt(floor['kappa'])} | {fmt(floor['agreement'], True)} | {fmt(floor['kappa_reweighted'])} | {fmt(floor['agreement_reweighted'], True)} | | | | |"]
    for c in configs:
        r, m, i = results[c], results[c]["majority"], conf[c]
        outputs = f"`{i['outputs']}`" if i.get("outputs") else ("votes in `submissions/`" if i.get("votes_source") else "votes only")
        L.append(f"| `{c}` | `{i['model']}` | {i['prompt']} | {r['passes']} | {fmt(m['kappa'])} | {fmt(m['agreement'], True)} | "
                 f"{fmt(m['kappa_reweighted'])} | {fmt(m['agreement_reweighted'], True)} | {fmt(r['unanimous_share'], True)} | "
                 f"{i['calls'] if i.get('calls') else 'n/a'} | {money(i['cost_usd']) if i.get('cost_usd') is not None else 'n/a'} | {outputs} |")
    L += ["", "## Single-pass view", "", "Each pass scored on its own against the labels, mean over the passes.", "",
          "| Configuration | Passes | Cohen's kappa | Raw agreement | Kappa, reweighted | Agreement, reweighted |", "|---|---|---|---|---|---|"]
    for c in configs:
        sp = [x for x in results[c]["single_pass"] if x["n"]]
        mean = lambda k: sum(x[k] for x in sp) / len(sp)
        L.append(f"| `{c}` | {len(sp)} | {fmt(mean('kappa'))} | {fmt(mean('agreement'), True)} | {fmt(mean('kappa_reweighted'))} | {fmt(mean('agreement_reweighted'), True)} |")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="compare against the committed files instead of writing")
    a = ap.parse_args()
    rows, configs, conf, weights, results, floor = compile_all()
    out_dir = os.path.join(VALIDATION_DIR, "results")
    files = {"table.md": curated_table(conf, results, floor),
             "table_full.md": full_table(conf, configs, results, floor, len(rows)),
             "results.json": json.dumps({"n_labelled": len(rows), "stratum_weights": weights, "floor": floor,
                                         "results": results}, indent=1) + "\n"}
    # the README carries the curated table between two marker comments; keep it in step
    readme_path = os.path.join(VALIDATION_DIR, "README.md")
    start, end = "<!-- table:start -->", "<!-- table:end -->"
    readme = open(readme_path).read() if os.path.exists(readme_path) else ""
    if start in readme and end in readme:
        head, rest = readme.split(start, 1)
        _, tail = rest.split(end, 1)
        files["README.md"] = head + start + "\n" + files["table.md"] + end + tail
    if a.check:
        stale = [n for n, body in files.items()
                 if not os.path.exists(os.path.join(out_dir if n != "README.md" else VALIDATION_DIR, n))
                 or open(os.path.join(out_dir if n != "README.md" else VALIDATION_DIR, n)).read() != body]
        if stale:
            print("stale:", ", ".join(stale)); sys.exit(1)
        print("tables up to date"); return
    for n, body in files.items():
        open(os.path.join(out_dir if n != "README.md" else VALIDATION_DIR, n), "w").write(body)
    print(files["table.md"])


if __name__ == "__main__":
    main()
